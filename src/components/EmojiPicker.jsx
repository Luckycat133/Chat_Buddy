const CATEGORY_ICONS = {
    recent: Clock,
    smileys: Smile,
    gestures: ThumbsUp,
    animals: Cat,
    food: Utensils,
    activities: Gamepad,
    travel: Plane,
    objects: Lightbulb,
    symbols: Heart
};

const CATEGORY_KEYS = {
    recent: 'recent_emoji',
    smileys: 'emoji_smileys',
    gestures: 'emoji_gestures',
    animals: 'emoji_animals',
    food: 'emoji_food',
    activities: 'emoji_activities',
    travel: 'emoji_travel',
    objects: 'emoji_objects',
    symbols: 'emoji_symbols'
};

export default function EmojiPicker({ onSelect, onClose }) {
    const { t } = useLanguage();
    const [activeCategory, setActiveCategory] = useState('smileys');
    const [searchQuery, setSearchQuery] = useState('');
    const [recentEmojis, setRecentEmojis] = useState(() => {
        try {
            return JSON.parse(localStorage.getItem('chat-buddy-recent-emojis') || '[]');
        } catch {
            return [];
        }
    });
    const pickerRef = useRef(null);

    // Close on outside click
    useEffect(() => {
        const handleClickOutside = (e) => {
            if (pickerRef.current && !pickerRef.current.contains(e.target)) {
                onClose?.();
            }
        };
        document.addEventListener('mousedown', handleClickOutside);
        return () => document.removeEventListener('mousedown', handleClickOutside);
    }, [onClose]);

    const handleEmojiClick = (emoji) => {
        // Add to recent
        const newRecent = [emoji, ...recentEmojis.filter(e => e !== emoji)].slice(0, 24);
        setRecentEmojis(newRecent);
        localStorage.setItem('chat-buddy-recent-emojis', JSON.stringify(newRecent));

        onSelect?.(emoji);
    };

    const categories = Object.keys(EMOJI_DATA);
    const displayEmojis = activeCategory === 'recent'
        ? recentEmojis
        : EMOJI_DATA[activeCategory] || [];

    return (
        <div
            ref={pickerRef}
            className="absolute bottom-full mb-2 left-0 w-72 bg-white rounded-lg shadow-xl border border-gray-200 overflow-hidden z-50"
        >
            {/* Header */}
            <div className="flex items-center justify-between px-3 py-2 border-b border-gray-100">
                <span className="font-medium text-sm text-gray-700">{t('emoji')}</span>
                <button
                    onClick={onClose}
                    className="p-1 hover:bg-gray-100 rounded text-gray-500"
                >
                    <X size={16} />
                </button>
            </div>

            {/* Search */}
            <div className="px-3 py-2 border-b border-gray-100">
                <div className="relative">
                    <Search size={14} className="absolute left-2 top-1/2 -translate-y-1/2 text-gray-400" />
                    <input
                        type="text"
                        value={searchQuery}
                        onChange={(e) => setSearchQuery(e.target.value)}
                        placeholder={t('search')}
                        className="w-full pl-7 pr-3 py-1.5 text-sm bg-gray-50 rounded border-none focus:outline-none focus:ring-1 focus:ring-[var(--color-primary)]"
                    />
                </div>
            </div>

            {/* Category tabs */}
            <div className="flex border-b border-gray-100 px-1 overflow-x-auto scrollbar-hide">
                {categories.map(cat => {
                    const Icon = CATEGORY_ICONS[cat];
                    return (
                        <button
                            key={cat}
                            onClick={() => setActiveCategory(cat)}
                            className={cn(
                                "p-2 flex-shrink-0 transition-colors",
                                activeCategory === cat
                                    ? "text-[var(--color-primary)] border-b-2 border-[var(--color-primary)]"
                                    : "text-gray-400 hover:text-gray-600"
                            )}
                            title={t(CATEGORY_KEYS[cat])}
                        >
                            <Icon size={18} />
                        </button>
                    );
                })}
            </div>

            {/* Emoji grid */}
            <div className="h-48 overflow-y-auto p-2">
                {displayEmojis.length === 0 ? (
                    <div className="flex items-center justify-center h-full text-gray-400 text-sm">
                        {activeCategory === 'recent' ? t('no_messages') : t('loading')}
                    </div>
                ) : (
                    <div className="grid grid-cols-8 gap-1">
                        {displayEmojis.map((emoji, index) => (
                            <button
                                key={`${emoji}-${index}`}
                                onClick={() => handleEmojiClick(emoji)}
                                className="w-8 h-8 flex items-center justify-center text-xl hover:bg-gray-100 rounded transition-colors"
                            >
                                {emoji}
                            </button>
                        ))}
                    </div>
                )}
            </div>
        </div>
    );
}
